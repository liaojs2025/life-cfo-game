"""Regenerate the game's compact opening observations from the offline source extract."""
import argparse
import datetime
import json
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXTRACT = ROOT / "scripts/opening-sources/observations.json"
DEST = ROOT / "dist/opening-observations.js"
INDICATORS = ("rate", "cpi", "unemployment")


def to_row(observation, opening_year):
    month = datetime.date.fromisoformat(observation["period"] + "-01")
    cutoff = datetime.date.fromisoformat(observation["availableBy"])
    if not month <= cutoff < datetime.date(opening_year, 1, 1):
        raise ValueError(f"Observation outside opening desk: {observation}")
    if observation["source"] == "us-cpi":
        previous = Decimal(observation["previous"])
        current = Decimal(observation["current"])
        change = (current / previous - 1) * 100
        value = float(change.quantize(Decimal("0.1"), rounding=ROUND_HALF_UP))
    else:
        value = observation["value"]
    period = observation.get("observationDate", observation["period"])
    if len(period) == 10 and not month <= datetime.date.fromisoformat(period) <= cutoff:
        raise ValueError(f"Quote outside observation period: {observation}")
    row = [observation["source"], period, observation["availableBy"], value]
    if "url" in observation:
        row.append(observation["url"])
    if observation.get("dateBound"):
        row.append(True)
    return row


def build():
    countries = json.loads(EXTRACT.read_text())
    assert set(countries) == {"us", "jp"}
    lines = ["// Generated by scripts/build-opening-indicators.py from the offline extract.",
             "// Rows contain source, observation period/date, availability bound, value, optional release URL and date-bound flag.",
             "export const OPENING_OBSERVATIONS = {"]
    for country, years in countries.items():
        assert set(map(int, years)) == set(range(1987, 2027))
        lines.append(f"  {country}: {{")
        for year, observations in sorted(years.items()):
            keys = ("rate", "cpi", "fx", "unemployment") if country == "jp" and int(year) <= 2003 else INDICATORS
            assert set(observations) == set(keys)
            values = [to_row(observations[key], int(year)) for key in keys]
            lines.append(f"    {year}: " + json.dumps(values, separators=(",", ":"), allow_nan=False) + ",")
        lines.append("  },")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check the committed table without writing")
    options = parser.parse_args()
    built = build()
    if options.check:
        if built != DEST.read_text():
            raise SystemExit("Opening observations have changed. Regenerate with scripts/build-opening-indicators.py.")
    else:
        DEST.write_text(built)
