import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, extname, relative } from 'node:path';
import { gzipSync } from 'node:zlib';

const root = resolve(import.meta.dirname, '..');
const assets = {};
const mime = { '.html':'text/html; charset=utf-8', '.js':'text/javascript; charset=utf-8', '.css':'text/css; charset=utf-8', '.svg':'image/svg+xml', '.jpg':'image/jpeg', '.png':'image/png' };
async function collect(directory) {
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a,b)=>a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') || entry.name === 'server' || entry.name === 'harbor-life.png') continue;
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) await collect(path);
    else {
      const type = mime[extname(path)];
      if (!type) throw new Error(`Unsupported public asset: ${entry.name}`);
      assets['/' + relative(resolve(root, 'dist'), path).replaceAll('\\', '/')] = [type, (await readFile(path)).toString('base64')];
    }
  }
}
await collect(resolve(root, 'dist'));
if (!assets['/index.html'] || !assets['/ai.js']) throw new Error('Missing game assets.');
const manifest = JSON.parse(await readFile(resolve(root, '.openai/hosting.json'), 'utf8'));
if (manifest.static || !manifest.project_id) throw new Error('Worker hosting manifest required.');
const providers = await readFile(resolve(root, 'dist/providers.js'), 'utf8');
const stream = await readFile(resolve(root, 'worker/stream.js'), 'utf8');
const handler = (await readFile(resolve(root, 'worker/handler.js'), 'utf8')).replace(/^import .*'(?:\.\.\/dist\/providers|\.\/stream)\.js';\n/gm, '');
const source = `// Generated by scripts/build-worker.mjs. No credentials are embedded.\nconst ASSET_MAP = ${JSON.stringify(assets)};\n${providers}\n${stream}\n${handler}`;
const compressed = gzipSync(source).byteLength;
if (compressed > 9.5 * 1024 * 1024) throw new Error('Worker exceeds artifact size budget.');
await mkdir(resolve(root, 'dist/server'), { recursive: true });
await mkdir(resolve(root, 'dist/.openai'), { recursive: true });
await writeFile(resolve(root, 'dist/server/index.js'), source);
await writeFile(resolve(root, 'dist/.openai/hosting.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Worker built: ${Object.keys(assets).length} assets, ${(compressed / 1024 / 1024).toFixed(2)} MiB compressed. No API credentials included.`);
