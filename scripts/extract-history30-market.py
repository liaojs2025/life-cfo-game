#!/usr/bin/env python3
"""Parse raw downloaded NYU, Yahoo and e-Stat files; FX is a visually audited PDF transcription.
See docs/DATA30.md for exact filenames, URLs and PDF duplicate-year treatment.
No missing values are synthesized; a changed source format fails visibly.
"""
from pathlib import Path
from html.parser import HTMLParser
from datetime import datetime
import json,hashlib,argparse
from zoneinfo import ZoneInfo
parser=argparse.ArgumentParser(description='Extract the audited 1995–2024 market window from downloaded source files.')
parser.add_argument('--source-dir',type=Path,required=True)
parser.add_argument('--retrieved-at',default='2026-11-25')
args=parser.parse_args()
root=Path(__file__).resolve().parents[1];src=args.source_dir
class Rows(HTMLParser):
 def __init__(self):super().__init__();self.rows=[];self.row=None;self.cell=None
 def handle_starttag(self,t,a):
  if t=='tr':self.row=[]
  if t in ['td','th']:self.cell=''
 def handle_data(self,d):
  if self.cell is not None:self.cell+=d
 def handle_endtag(self,t):
  if t in ['td','th'] and self.cell is not None:
   if self.row is not None:self.row.append(' '.join(self.cell.split()))
   self.cell=None
  if t=='tr' and self.row is not None:self.rows.append(self.row);self.row=None
p=Rows();p.feed((src/'nyu.txt').read_text(errors='replace'))
nyu={int(r[0]):{'sp500':float(r[1].rstrip('%'))/100,'goldUSD':float(r[7].rstrip('%'))/100} for r in p.rows if r and r[0].isdigit() and 1993<=int(r[0])<=2024}
def yahoo(name):
 r=json.loads((src/(name+'.txt')).read_text())['chart']['result'][0];o={}
 for ts,c in zip(r['timestamp'],r['indicators']['quote'][0]['close']):
  d=datetime.fromtimestamp(ts,ZoneInfo(r['meta']['exchangeTimezoneName']))
  # Yahoo monthly timestamp denotes month start; close is final session of that month.
  if d.month==12 and c is not None and 1993<=d.year<=2024:o[d.year]=round(c,2)
 assert len(o)==32,(name,len(o))
 return o
nasdaq=yahoo('nasdaq-yahoo');nikkei=yahoo('nikkei-yahoo')
x=json.loads((src/'estat-topix.txt').read_text())['GET_STATS']['STATISTICAL_DATA']['DATA_INF']['DATA_OBJ']
topix={int(r['VALUE']['@time'][:4]):float(r['VALUE']['$']) for r in x}
# Cabinet Office Table 8.2, p.15 (PDF p.17), visually checked: source prints 2021 twice with same 115.12; keep one year.
fx_vals=[99.83,102.91,115.98,129.92,115.20,102.08,114.90,131.47,119.37,106.97,103.78,117.48,118.92,113.12,90.28,92.13,81.51,77.57,86.32,105.37,119.80,120.42,117.11,112.65,110.40,109.15,103.33,115.12,132.14,141.40,157.89]
fx=dict(zip(range(1994,2025),fx_vals));assert len(fx)==31
rows=[]
for year in range(1994,2025):
 r={'year':year,'sp500TotalReturn':nyu[year]['sp500'],'nasdaqClose':nasdaq[year],'nasdaqPriceReturn':round(nasdaq[year]/nasdaq[year-1]-1,12),'topixClose':topix[year],'topixPriceReturn':round(topix[year]/topix[year-1]-1,12),'nikkeiClose':nikkei[year],'nikkeiPriceReturn':round(nikkei[year]/nikkei[year-1]-1,12),'goldUSDPriceReturn':nyu[year]['goldUSD'],'jpyPerUSD':fx[year]}
 if year>=1995:r['goldJPYPriceReturn']=round((1+nyu[year]['goldUSD'])*fx[year]/fx[year-1]-1,12)
 rows.append(r)
(root/'dist/history30-markets.js').write_text('// Source-derived annual observations; generated by scripts/build-history30-market.py.\n// 1994 is briefing/baseline only. No missing observations are filled.\nexport const MARKET_OBSERVATIONS = '+json.dumps(rows,ensure_ascii=False,indent=2)+';\n')
# Compact numeric source extract, not republishing full daily/monthly index files.
out=root/'scripts/history30-sources';out.mkdir(exist_ok=True)
(out/'annual-observations.json').write_text(json.dumps({'retrievedAt':args.retrieved_at,'basis1993':{'nasdaqClose':nasdaq[1993],'nikkeiClose':nikkei[1993],'topixClose':topix[1993]},'fxNote':'ESRI 2024 report Table 8.2 repeats 2021/115.12; duplicate removed by year after visual review.','observations':rows},ensure_ascii=False,indent=2)+'\n')
manifest=[]
for n in ['nyu.txt','nasdaq-yahoo.txt','nikkei-yahoo.txt','estat-topix.txt','estat-info.txt','esri-fx.pdf']:
 d=(src/n).read_bytes();manifest.append({'localResearchFile':n,'bytes':len(d),'sha256':hashlib.sha256(d).hexdigest()})
(out/'source-hashes.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Wrote 31 annual observations; 30 complete rounds; raw hashes recorded. Last observation:',rows[-1])
