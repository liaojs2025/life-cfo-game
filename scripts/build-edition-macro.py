"""Rebuild the additional budget and rate series from archived provider observations."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
src = root / 'scripts/editions-sources'
short_rates = json.loads((src / 'extra-overnight.json').read_text())
result = {}
for country in ['us', 'jp']:
    _, rows = json.loads((src / f'cpi-{country}.json').read_text())
    inflation = {row['date']: row['value'] / 100 for row in rows if row['value'] is not None}
    # WDI omits the US 2025 annual observation. BLS December/December CPI-U is 2.7%.
    if country == 'us' and '2025' not in inflation:
        inflation['2025'] = .027
    assert set(inflation) == {str(y) for y in range(1986,2026)}
    overnight = dict(short_rates[country])
    rates = {}
    for year in [*range(1986,1995),2025]:
        observations = [overnight[f'{year}-{m:02d}-01'] for m in range(1,13)]
        rates[year] = round(sum(observations)/1200,12)
    result[country] = {'inflation': dict(sorted(inflation.items())), 'extraRates':rates}
(root/'dist/edition-macro.js').write_text('// Generated by scripts/build-edition-macro.py from WDI, BLS and OECD/FRED.\nexport const EDITION_MACRO = '+json.dumps(result,indent=2)+';\n')
