#!/usr/bin/env python3
"""Rebuild annual market module from the audited compact source observations.
No network, no missing-value fill. The original source URLs and hashes are in DATA30.
"""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/history30-sources/annual-observations.json'
data = json.loads(SOURCE.read_text())
rows = data['observations']
assert [row['year'] for row in rows] == list(range(1994, 2025))
previous = data['basis1993']
for row in rows:
    for close, result in [('nasdaqClose','nasdaqPriceReturn'), ('topixClose','topixPriceReturn'), ('nikkeiClose','nikkeiPriceReturn')]:
        actual = round(row[close] / previous[close] - 1, 12)
        assert math.isclose(actual, row[result], abs_tol=1e-12), (row['year'], result)
        row[result] = actual
    if row['year'] >= 1995:
        actual = round((1 + row['goldUSDPriceReturn']) * row['jpyPerUSD'] / previous['jpyPerUSD'] - 1, 12)
        assert math.isclose(actual, row['goldJPYPriceReturn'], abs_tol=1e-12), row['year']
        row['goldJPYPriceReturn'] = actual
    assert all(math.isfinite(value) for value in row.values())
    previous = row
out = ROOT / 'dist/history30-markets.js'
out.write_text('// Source-derived annual observations; generated by scripts/build-history30-market.py.\n'
               '// 1994 is briefing/baseline only. No missing observations are filled.\n'
               'export const MARKET_OBSERVATIONS = ' + json.dumps(rows, ensure_ascii=False, indent=2) + ';\n')
print(f'Rebuilt {out.name}: 31 observations, 30 complete game years; no fills.')
