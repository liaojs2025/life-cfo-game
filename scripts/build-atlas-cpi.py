"""Build the end-of-period CPI series offline, or extract a new snapshot from official CSVs."""
import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / 'scripts/atlas-sources/cpi-close.csv'
OUTPUT = ROOT / 'dist/atlas-cpi-levels.js'
MONTHS = [f'{year}-12' for year in range(1986, 2026)] + ['2026-09']


def extract(us_file, jp_file):
    with us_file.open(encoding='utf-8-sig', newline='') as file:
        rows = csv.DictReader(file)
        us = {r['observation_date'][:7]: r['CPIAUCNS'] for r in rows}
    with jp_file.open(encoding='cp932', newline='') as file:
        rows = csv.reader(file)
        ja, en, codes = next(rows), next(rows), next(rows)
        column = codes.index('0001')
        if ja[column] != '総合' or en[column] != 'All items':
            raise ValueError('Japanese source must be nationwide headline CPI, all items.')
        jp = {r[0][:4] + '-' + r[0][4:]: r[column] for r in rows if r[0].isdigit()}
    with SNAPSHOT.open('w', encoding='utf-8', newline='') as file:
        writer = csv.writer(file, lineterminator='\n')
        writer.writerow(['month', 'us', 'jp'])
        writer.writerows((month, us[month], jp[month]) for month in MONTHS)


def build():
    with SNAPSHOT.open(encoding='utf-8', newline='') as file:
        rows = list(csv.DictReader(file))
    if [row['month'] for row in rows] != MONTHS:
        raise ValueError('CPI snapshot months must match the settlement calendar.')
    lines = ['// Generated by scripts/build-atlas-cpi.py from the archived monthly closes.',
             'export const CPI_LEVELS = {']
    for country in ('us', 'jp'):
        lines.append(f'  {country}: {{')
        for row in rows:
            value = row[country]
            if not (value.replace('.', '', 1).isdigit() and float(value) > 0):
                raise ValueError(f'Invalid CPI level in {row}')
            lines.append(f'    "{row["month"]}": {value},')
        lines.append('  },')
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    options = parser.add_mutually_exclusive_group()
    options.add_argument('--extract', nargs=2, metavar=('FRED_CSV', 'ESTAT_CSV'), type=Path)
    options.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.extract:
        extract(*args.extract)
    output = build()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != output:
            raise SystemExit('CPI module differs from the offline snapshot.')
    else:
        OUTPUT.write_text(output, encoding='utf-8')
